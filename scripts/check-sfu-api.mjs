import assert from 'node:assert/strict'
import { build } from 'esbuild'

const built = await build({ entryPoints: ['src/lib/sfu-api.server.ts'], bundle: true, write: false, platform: 'node', format: 'esm' })
const { createSfuApi } = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].contents).toString('base64')}`)
const requests = []
const responses = []
const api = createSfuApi({ appId: 'app', appSecret: 'synthetic', fetcher: async (url, init) => {
  requests.push({ url, init })
  return responses.shift()
} })
const respond = (value, status = 200) => responses.push(Response.json(value, { status }))
respond({ sessionId: 'session' }, 201)
assert.equal(await api.createSession(), 'session')
assert.equal(requests[0].url, 'https://rtc.live.cloudflare.com/v1/apps/app/sessions/new')
assert.equal(requests[0].init.body, undefined)
assert.equal(requests[0].init.headers.Authorization, 'Bearer synthetic')
respond({ sessionDescription: { type: 'answer', sdp: 'answer' }, tracks: [{ location: 'local', mid: '0', trackName: 'mic' }] })
assert.equal((await api.createTrack({ sessionId: 'session', track: { location: 'local', mid: '0', trackName: 'mic' }, sessionDescription: { type: 'offer', sdp: 'offer' } })).track.mid, '0')
assert.deepEqual(JSON.parse(requests.at(-1).init.body), { sessionDescription: { type: 'offer', sdp: 'offer' }, tracks: [{ location: 'local', mid: '0', trackName: 'mic' }] })
respond({ requiresImmediateRenegotiation: true, sessionDescription: { type: 'offer', sdp: 'offer' }, tracks: [{ location: 'remote', sessionId: 'pub', trackName: 'voice', mid: '1' }] })
assert.equal((await api.createTrack({ sessionId: 'session', track: { location: 'remote', sessionId: 'pub', trackName: 'voice' } })).requiresImmediateRenegotiation, true)
respond({})
await api.renegotiate({ sessionId: 'session', sessionDescription: { type: 'answer', sdp: 'answer' } })
assert.equal(requests.at(-1).init.method, 'PUT')
respond({ tracks: [{ trackName: 'voice', adapterId: 'adapter', sessionId: 'publisher', endpoint: 'wss://example.com/ingest' }] })
assert.deepEqual(await api.createAdapter({ location: 'local', trackName: 'voice', endpoint: 'wss://example.com/ingest' }), { adapterId: 'adapter', sessionId: 'publisher' })
respond({ tracks: [{ trackName: 'mic', errorCode: 'websocket_handshake_failed', errorDescription: 'failed' }] }, 503)
await assert.rejects(api.createAdapter({ location: 'remote', sessionId: 'session', trackName: 'mic', endpoint: 'wss://example.com/stream' }), /SFU adapter creation failed/)
respond({ tracks: [{ mid: '1' }] })
await api.closeTrack({ sessionId: 'session', mid: '1' })
assert.deepEqual(JSON.parse(requests.at(-1).init.body), { tracks: [{ mid: '1' }], force: true })
respond({ tracks: [{ adapterId: 'adapter' }] })
await api.closeAdapter('adapter')
assert.deepEqual(JSON.parse(requests.at(-1).init.body), { tracks: [{ adapterId: 'adapter' }] })
respond({ tracks: [{ adapterId: 'adapter', errorCode: 'internal_error' }] })
await assert.rejects(api.closeAdapter('adapter'), /SFU adapter close failed/)
respond({ tracks: [] })
await assert.rejects(api.closeAdapter('adapter'), /SFU adapter close failed/)
respond({ requiresImmediateRenegotiation: true, sessionDescription: { type: 'offer', sdp: 'offer' }, tracks: [{ sessionId: 'pub', trackName: 'voice', mid: '1' }] })
await api.createTrack({ sessionId: 'a/b', track: { location: 'remote', sessionId: 'pub', trackName: 'voice' } })
assert.ok(requests.at(-1).url.includes('/sessions/a%2Fb/tracks/new'))
await assert.rejects(api.createTrack({ sessionId: '..', track: { location: 'remote', sessionId: 'pub', trackName: 'voice' } }), /Invalid/)
respond({ sessionId: '' }, 201)
await assert.rejects(api.createSession(), /SFU response is invalid/)
respond({ tracks: [{ trackName: 'voice', adapterId: 'adapter', endpoint: 'wss://example.com/ingest' }] })
await assert.rejects(api.createAdapter({ location: 'local', trackName: 'voice', endpoint: 'wss://example.com/ingest' }), /SFU adapter creation failed/)
respond({ tracks: [{ trackName: 'voice', adapterId: 'adapter', sessionId: 42 }] })
await assert.rejects(api.createAdapter({ location: 'local', trackName: 'voice', endpoint: 'wss://example.com/ingest' }), error => error.adapterId === 'adapter')
respond({ tracks: [{ trackName: 'mic', errorCode: 'track_not_found' }] })
await assert.rejects(api.createTrack({ sessionId: 'session', track: { location: 'local', mid: '0', trackName: 'mic' }, sessionDescription: { type: 'offer', sdp: 'offer' } }), /SFU track creation failed/)
console.log('SFU API checks passed')
