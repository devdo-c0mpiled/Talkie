import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { build } from 'esbuild'
import { Miniflare } from 'miniflare'

const bundle = await build({
  entryPoints: ['scripts/check-chat-outbound-worker.mjs'], bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', external: ['node:*'],
  plugins: [{ name: 'synthetic-bindings', setup(build) {
    build.onResolve({ filter: /^cloudflare:workers$/ }, () => ({ path: 'env', namespace: 'mock-env' }))
    build.onLoad({ filter: /.*/, namespace: 'mock-env' }, () => ({ contents: 'export const env = globalThis.__testEnv = {}', loader: 'js' }))
    build.onResolve({ filter: /^@tanstack\/react-start\/server-only$/ }, () => ({ path: 'server-only', namespace: 'mock-env' }))
  } }],
})
const worker = new Miniflare({ workers: [{ config: {
  name: 'outbound-test', compatibilityDate: '2026-11-08', compatibilityFlags: ['nodejs_compat'],
  env: { DB: { type: 'd1', id: 'synthetic-outbound-db' } },
  manifest: { mainModule: 'worker.mjs', modules: { 'worker.mjs': { type: 'esm', contents: bundle.outputFiles[0].text } } },
} }] })
const run = async (body) => (await worker.dispatchFetch('https://example.test/', { method: 'POST', body: JSON.stringify(body) })).json()
try {
  for (const number of ['001123456789', '002123456789', '006123456789', '+82001123456789', '06012345678', '0912345678']) {
    assert.equal(await run({ type: 'normalize', number }), null, `reject ${number}`)
  }
  for (const [number, expected] of [['02-1234-5678', '0212345678'], ['010-1234-5678', '01012345678'], ['+82 31 123 4567', '0311234567'], ['070-1234-5678', '07012345678'], ['050-1234-5678', '05012345678'], ['1588-1234', '15881234']]) {
    assert.equal(await run({ type: 'normalize', number }), expected, `accept ${number}`)
  }
  const db = await worker.getD1Database('DB')
  for (const statement of (await readFile('migrations/0004_live_call_transcripts.sql', 'utf8')).split(';').filter(x => x.trim())) await db.prepare(statement).run()
  const first = await run({ action: 'action-1', mode: 'webhook-first' })
  assert.deepEqual(first, { callId: 'CA_webhook' })
  const events = await run({ type: 'events' })
  assert.equal(events.length, 1)
  assert.equal(events[0].payload.To, '0212345678')
  assert.equal(events[0].payload.From, '07012340000')
  assert.equal(new URL(events[0].payload.Url).origin, 'https://example.test')
  assert.match(new URL(events[0].payload.Url).searchParams.get('intent'), /^[a-f0-9]{64}$/)
  assert.ok(!('AgentId' in events[0].payload) && !('CallContext' in events[0].payload))
  assert.equal((await run({ action: 'action-1' })).error, 'unknown')
  assert.equal((await run({ action: 'action-2', mode: 'unknown' })).error, 'unknown')
  assert.equal((await run({ action: 'action-5', mode: 'rejected' })).error, 'rejected')
  assert.equal((await run({ type: 'events' })).length, 3)
  const statusRequest = async (mode) => worker.dispatchFetch('https://example.test/', { method: 'POST', body: JSON.stringify({ type: 'status', callId: 'CA_webhook', mode }) })
  const unavailable = await statusRequest('status-failure')
  assert.equal(unavailable.status, 502)
  assert.equal(unavailable.headers.get('cache-control'), 'no-store')
  assert.equal((await statusRequest('status-malformed')).status, 502)
  const status = await statusRequest('status-ok')
  assert.equal(status.status, 200)
  assert.equal(status.headers.get('cache-control'), 'no-store')
  assert.equal((await status.json()).state, 'calling')
  assert.deepEqual(await run({ type: 'result', callId: 'CA_webhook', mode: 'status-failure' }), { state: 'unknown', outcome: 'status-unavailable', analysis: { status: 'unavailable', reason: 'status-unavailable' } })
  const oversized = await run({ action: 'oversized', instruction: '가'.repeat(4001) })
  assert.equal(oversized.error, 'instruction-too-long')
  assert.equal((await run({ type: 'events' })).length, 3)
  assert.equal((await (await statusRequest('status-no-answer')).json()).state, 'done')
  assert.equal((await run({ type: 'result', callId: 'CA_webhook', mode: 'status-no-answer' })).analysis.reason, 'call-not-connected')
  assert.equal((await run({ type: 'result', callId: 'CA_webhook', mode: 'status-busy' })).analysis.reason, 'call-not-connected')
  const beforeFlush = await (await statusRequest('status-completed')).json()
  assert.equal(beforeFlush.state, 'calling')
  await db.prepare('UPDATE live_calls SET bridge_finished_at = ? WHERE call_id = ?').bind(Date.now(), 'CA_webhook').run()
  const afterFlush = await (await statusRequest('status-completed')).json()
  assert.equal(afterFlush.state, 'done')
  assert.equal(afterFlush.transcriptIncomplete, undefined)
  await db.prepare('UPDATE live_calls SET bridge_finished_at = NULL, provider_completed_at = ? WHERE call_id = ?').bind(Date.now() - 30_001, 'CA_webhook').run()
  const fallback = await (await statusRequest('status-completed')).json()
  assert.equal(fallback.state, 'done')
  assert.equal(fallback.transcriptIncomplete, true)
  const incomplete = await run({ type: 'result', callId: 'CA_webhook', mode: 'status-completed' })
  assert.equal(incomplete.transcriptIncomplete, true)
  assert.deepEqual(await run({ type: 'recording-counts' }), { recordings: 3, transcriptions: 0 })
  const failedRecording = await run({ type: 'result', callId: 'CA_webhook', mode: 'recording-failure' })
  assert.equal(failedRecording.transcriptIncomplete, true)
  assert.deepEqual(await run({ type: 'recording-counts' }), { recordings: 4, transcriptions: 0 })
  const recorded = await run({ type: 'result', callId: 'CA_webhook', mode: 'recording-delayed' })
  assert.equal(recorded.transcript, 'Synthetic recording transcript')
  assert.equal(recorded.transcriptIncomplete, true)
  assert.equal((await run({ type: 'result', callId: 'CA_webhook', mode: 'recording' })).transcript, recorded.transcript)
  assert.deepEqual(await run({ type: 'recording-counts' }), { recordings: 7, transcriptions: 1 })
  await db.prepare('INSERT INTO live_call_transcripts (call_id, event_id, role, text, start_ms, end_ms) VALUES (?, ?, ?, ?, ?, ?)')
    .bind('CA_webhook', 'event-1', 'business', 'Live transcript', 0, 1).run()
  const liveIncomplete = await run({ type: 'result', callId: 'CA_webhook', mode: 'recording' })
  assert.equal(liveIncomplete.transcript, 'Business: Live transcript')
  assert.equal(liveIncomplete.analysis.status, 'available', JSON.stringify(liveIncomplete.analysis))
  assert.equal(liveIncomplete.analysis.reservation.status, 'unknown', 'an incomplete call cannot establish a reservation')
  await db.prepare('UPDATE live_calls SET bridge_finished_at = ? WHERE call_id = ?').bind(Date.now(), 'CA_webhook').run()
  const liveComplete = await run({ type: 'result', callId: 'CA_webhook', mode: 'recording' })
  assert.equal(liveComplete.analysis.status, 'available', JSON.stringify(liveComplete.analysis))
  assert.equal(liveComplete.analysis.reservation.status, 'confirmed')
  assert.equal(liveComplete.analysis.reservation.assessment, 'model-estimate')
  assert.equal((await run({ type: 'result', callId: 'CA_webhook', mode: 'analysis-error' })).analysis.reason, 'model-unavailable')
  await db.prepare('UPDATE live_call_transcripts SET text = ? WHERE call_id = ?').bind(`Live transcript${'가'.repeat(6000)}`, 'CA_webhook').run()
  const truncated = await run({ type: 'result', callId: 'CA_webhook', mode: 'recording' })
  assert.equal(truncated.transcriptIncomplete, true)
  assert.equal(truncated.analysis.reservation.status, 'unknown', 'a truncated call cannot establish a reservation')
  await db.prepare('UPDATE live_call_transcripts SET text = ? WHERE call_id = ?').bind('Live transcript', 'CA_webhook').run()
  await db.prepare(`WITH RECURSIVE n(x) AS (SELECT 2 UNION ALL SELECT x + 1 FROM n WHERE x < 2000)
    INSERT INTO live_call_transcripts (call_id, event_id, role, text, start_ms, end_ms)
    SELECT 'CA_webhook', 'event-' || x, 'business', '.', x, x + 1 FROM n`).run()
  const capped = await run({ type: 'result', callId: 'CA_webhook', mode: 'recording' })
  assert.ok(capped.transcript.length < 6000)
  assert.equal(capped.transcriptIncomplete, true)
  assert.equal(capped.analysis.reservation.status, 'unknown', 'a transcript at the storage cap cannot establish a reservation')
  assert.deepEqual(await run({ type: 'recording-counts' }), { recordings: 7, transcriptions: 1 })
  const legacyCall = 'CA_legacy'
  const legacyRequest = (body) => worker.dispatchFetch('https://example.test/', { method: 'POST', body: JSON.stringify({ callId: legacyCall, ...body }) })
  const legacyStatus = await legacyRequest({ type: 'status', mode: 'legacy-pages', withoutDialConfig: true })
  assert.equal(legacyStatus.status, 200, 'existing lookup does not require new-call configuration')
  const legacyBody = await legacyStatus.json()
  assert.equal(legacyBody.state, 'done')
  assert.equal(legacyBody.transcriptIncomplete, true, 'missing local row does not prove transcript completeness')
  assert.equal(legacyBody.lines.length, 1, 'multiple event pages are merged by utterance')
  assert.equal((await legacyRequest({ type: 'status', invalidReference: true })).status, 404)
  for (const [mode, state] of [['legacy-404', 'done'], ['legacy-calling-404', 'calling']]) {
    const response = await legacyRequest({ type: 'status', mode })
    assert.equal(response.status, 200, 'missing events do not hide a verified provider status')
    const body = await response.json()
    assert.equal(body.state, state)
    assert.equal(body.transcriptIncomplete, true)
    assert.deepEqual(body.lines, [])
  }
  for (const mode of ['legacy-error', 'legacy-forbidden', 'legacy-malformed', 'legacy-role']) {
    const response = await legacyRequest({ type: 'status', mode })
    assert.equal(response.status, 502, `${mode} must not appear as an empty transcript`)
    const result = await (await legacyRequest({ type: 'result', mode })).json()
    assert.equal(result.transcriptIncomplete, true)
    assert.equal(result.analysis.status, 'unavailable')
  }
  const beforeDbFailure = await run({ type: 'legacy-counts' })
  assert.equal((await legacyRequest({ type: 'status', mode: 'legacy-db-error' })).status, 502)
  assert.equal((await (await legacyRequest({ type: 'result', mode: 'legacy-db-error' })).json()).state, 'unknown')
  assert.deepEqual(await run({ type: 'legacy-counts' }), beforeDbFailure, 'DB errors do not initiate legacy lookup or recording fallback')
  const partial = await (await legacyRequest({ type: 'status', mode: 'legacy-partial' })).json()
  assert.equal(partial.lines[0].final, false)
  assert.equal(partial.transcriptIncomplete, true)
  const beforeCap = await run({ type: 'legacy-counts' })
  const cappedLegacy = await (await legacyRequest({ type: 'status', mode: 'legacy-cap' })).json()
  assert.equal(cappedLegacy.transcriptIncomplete, true, 'a capped event listing is not complete')
  assert.equal((await run({ type: 'legacy-counts' })).events, beforeCap.events + 5)
  const legacyResult = await (await legacyRequest({ type: 'result', mode: 'legacy-pages' })).json()
  assert.equal(legacyResult.transcriptIncomplete, true)
  assert.equal(legacyResult.analysis.reservation.status, 'unknown', 'legacy data cannot establish a reservation')
  const legacyReport = await (await legacyRequest({ type: 'report', mode: 'legacy-pages' })).json()
  assert.equal(legacyReport.transcriptIncomplete, true)
  assert.deepEqual(legacyReport.lines, [], 'incomplete transcript cannot produce a result page')
  const recording = await (await legacyRequest({ type: 'result', mode: 'legacy-404', callId: 'CA_missing_events' })).json()
  assert.equal(recording.transcriptIncomplete, true)
  assert.equal(recording.analysis.status, 'unavailable')
  const empty = await (await legacyRequest({ type: 'result', mode: 'legacy-empty', callId: 'CA_empty_events' })).json()
  assert.equal(empty.transcriptIncomplete, true, 'empty events cannot establish the source or completeness')
  const redirectCounts = await run({ type: 'legacy-counts' })
  const redirect = await (await legacyRequest({ type: 'result', mode: 'legacy-redirect', callId: 'CA_bad_redirect' })).json()
  assert.equal(redirect.transcript, undefined, 'undocumented redirects must not be followed')
  assert.equal((await run({ type: 'legacy-counts' })).recordings, redirectCounts.recordings + 1)
  const beforeStorage = await run({ type: 'legacy-counts' })
  const signed = await (await legacyRequest({ type: 'result', mode: 'legacy-gcs', callId: 'CA_signed' })).json()
  assert.equal(signed.transcript, 'Synthetic recording transcript')
  assert.equal(signed.transcriptIncomplete, true)
  assert.equal((await run({ type: 'legacy-counts' })).storage, beforeStorage.storage + 1, 'trusted storage is fetched without credentials')
  for (const mode of ['legacy-port', 'legacy-credentials', 'legacy-no-sign']) {
    const count = (await run({ type: 'legacy-counts' })).storage
    const result = await (await legacyRequest({ type: 'result', mode, callId: `CA_${mode}` })).json()
    assert.equal(result.transcript, undefined)
    assert.equal((await run({ type: 'legacy-counts' })).storage, count, `${mode} must be rejected before storage fetch`)
  }
  const double = await (await legacyRequest({ type: 'result', mode: 'legacy-double', callId: 'CA_double' })).json()
  assert.equal(double.transcript, undefined, 'a second redirect is not followed')
  console.log('Outbound URL, webhook race, duplicate and unknown checks passed with synthetic D1 and provider')
} finally { await worker.dispose() }
